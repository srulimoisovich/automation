#!/bin/sh
# Скрипт запуска контейнера (entrypoint) для лабораторной работы №3.
# Он выполняется при каждом старте контейнера: настраивает часовой пояс,
# сохраняет переменные окружения для cron, создаёт журнал, устанавливает
# задания cron и запускает демон cron.

# Настройка часового пояса.
# Значение берётся из переменной TZ (задаётся в docker-compose.yml),
# если её нет, используется Europe/Chisinau. Без этого cron работал бы по UTC.
set_timezone() {
    # Берём часовой пояс из окружения или значение по умолчанию
    TZ="${TZ:-Europe/Chisinau}"
    # Делаем /etc/localtime ссылкой на файл нужного пояса из пакета tzdata
    ln -snf "/usr/share/zoneinfo/$TZ" /etc/localtime
    # Записываем имя пояса в /etc/timezone (так принято в Debian/Ubuntu)
    echo "$TZ" > /etc/timezone
    # Показываем, какое время теперь видит система
    echo "Часовой пояс: $TZ, текущее время: $(date '+%Y-%m-%d %H:%M:%S %Z')"
}

# Создание файла журнала /var/log/cron.log.
# В этот файл задания cron дописывают свой вывод (>> /var/log/cron.log 2>&1).
# Права 666 позволяют писать в журнал любому пользователю.
create_log_file() {
    echo "Создаём файл журнала /var/log/cron.log..."
    # Создаём пустой файл (если он уже есть, только обновится время изменения)
    touch /var/log/cron.log
    # Разрешаем чтение и запись всем пользователям
    chmod 666 /var/log/cron.log
    echo "Журнал /var/log/cron.log готов, сюда будут дописывать вывод задания cron"
}

# Установка заданий cron.
# Файл cronjob из образа копируется в /etc/cron.d, где cron ищет системные задания.
# Файл должен принадлежать root и иметь права 0644, иначе cron его пропустит.
install_cronjob() {
    # Копируем файл заданий в каталог системных заданий cron
    cp /lab03/cronjob /etc/cron.d/currency_rates
    # Выставляем права: запись только для root, чтение для всех
    chmod 0644 /etc/cron.d/currency_rates
    echo "Задания cron установлены в /etc/cron.d/currency_rates"
}

# Слежение за журналом.
# tail -f выводит новые строки cron.log в стандартный вывод контейнера,
# поэтому их видно в docker compose logs.
monitor_logs() {
    echo "=== Следим за журналом cron ==="
    # Выводим новые строки журнала по мере их появления
    tail -f /var/log/cron.log
}

# Запуск демона cron.
# Ключ -f оставляет cron на переднем плане, а exec заменяет им этот скрипт,
# поэтому cron становится главным процессом и контейнер не завершается.
run_cron() {
    echo "=== Запускаем демон cron в режиме переднего плана... ==="
    # Заменяем текущий процесс демоном cron
    exec cron -f
}

# Шаг 1. Настраиваем часовой пояс
set_timezone
# Шаг 2. Сохраняем переменные окружения в /etc/environment.
# cron не передаёт заданиям окружение контейнера, а /etc/environment
# читается модулем pam_env при запуске каждого задания.
env > /etc/environment
# Шаг 3. Создаём файл журнала
create_log_file
# Шаг 4. Устанавливаем задания cron
install_cronjob
# Шаг 5. Запускаем слежение за журналом в фоне
monitor_logs &
# Шаг 6. Запускаем cron (последняя команда, дальше скрипт не идёт)
run_cron
